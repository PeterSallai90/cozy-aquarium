class CompletenessTest(CheckTranslationsTestBase):
    def test_key_missing_in_a_po_fails_and_names_only_that_file(self) -> None:
        for name, other in (("en.po", "hu.po"), ("hu.po", "en.po")):
            with self.subTest(file=name):
                self.baseline()
                header = po_header(name[:2])
                self.write(f"game/localization/{name}", header + plural_entry(PLURAL, PLURAL + ".plural", "a", "b"))
                lines = self.assert_fails_naming(name, SINGULAR)
                self.assertFalse(any(other in line for line in self.error_lines(lines)), lines)

    def test_empty_msgstr_fails(self) -> None:
        for name in ("en.po", "hu.po"):
            with self.subTest(file=name):
                self.baseline()
                text = (self.root / "game/localization" / name).read_text(encoding="utf-8")
                start = text.index(f'msgid "{SINGULAR}"')
                end = text.index("\n\n", start) if "\n\n" in text[start:] else len(text)
                block = text[start:end]
                new_block = f'msgid "{SINGULAR}"\nmsgstr ""'
                self.write(f"game/localization/{name}", text.replace(block, new_block, 1))
                self.assert_fails_naming(name, SINGULAR)

    def test_whitespace_only_msgstr_is_not_accepted_as_a_translation(self) -> None:
        self.baseline()
        self.edit("game/localization/hu.po", 'msgstr "Új akvárium"', 'msgstr "   "')
        self.assert_fails_naming("hu.po", SINGULAR)

    def test_empty_first_plural_form_fails(self) -> None:
        for name in ("en.po", "hu.po"):
            with self.subTest(file=name):
                self.baseline()
                text = (self.root / "game/localization" / name).read_text(encoding="utf-8")
                self.write(
                    f"game/localization/{name}",
                    text.replace('msgstr[0] "%d', 'msgstr[0] ""\n#', 1),
                )
                self.assert_fails_naming(name, PLURAL)

    def test_empty_second_plural_form_fails(self) -> None:
        for name, translation in (("en.po", "%d fishes"), ("hu.po", "%d hal")):
            with self.subTest(file=name):
                self.baseline()
                text = (self.root / "game/localization" / name).read_text(encoding="utf-8")
                self.assertIn(f'msgstr[1] "{translation}"', text)
                self.write(
                    f"game/localization/{name}",
                    text.replace(f'msgstr[1] "{translation}"', 'msgstr[1] ""'),
                )
                self.assert_fails_naming(name, PLURAL)

    def test_missing_second_plural_form_fails(self) -> None:
        for name, translation in (("en.po", "%d fishes"), ("hu.po", "%d hal")):
            with self.subTest(file=name):
                self.baseline()
                text = (self.root / "game/localization" / name).read_text(encoding="utf-8")
                self.write(
                    f"game/localization/{name}",
                    text.replace(f'msgstr[1] "{translation}"\n', ""),
                )
                self.assert_fails_naming(name, PLURAL)

    def test_a_third_plural_form_fails(self) -> None:
        self.baseline()
        self.edit("game/localization/hu.po", 'msgstr[1] "%d hal"\n', 'msgstr[1] "%d hal"\nmsgstr[2] "%d hal"\n')
        self.assert_fails_naming("hu.po", PLURAL)

    def test_singular_entry_for_a_plural_key_fails(self) -> None:
        self.baseline()
        self.write(
            "game/localization/hu.po",
            po_header("hu") + singular(SINGULAR, "Új akvárium") + singular(PLURAL, "hal"),
        )
        self.assert_fails_naming("hu.po", PLURAL)

    def test_plural_entry_for_a_singular_key_fails(self) -> None:
        self.baseline()
