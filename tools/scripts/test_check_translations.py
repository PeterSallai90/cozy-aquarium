class EncodingTest(CheckTranslationsTestBase):
    BOM = b"\xef\xbb\xbf"

    def with_bytes(self, rel: str, transform: Callable[[bytes], bytes]) -> None:
        data = (self.root / rel).read_bytes()
        self.write_raw(rel, transform(data))

    def test_bom_in_each_file_fails(self) -> None:
        for name in ("messages.pot", "en.po", "hu.po", "extra_keys.txt"):
            with self.subTest(file=name):
                self.baseline()
                self.with_bytes(f"game/localization/{name}", lambda data: self.BOM + data)
                self.assert_fails_naming(name)

    def test_crlf_in_each_file_fails(self) -> None:
        for name in ("messages.pot", "en.po", "hu.po", "extra_keys.txt"):
            with self.subTest(file=name):
                self.baseline()
                self.with_bytes(
                    f"game/localization/{name}", lambda data: data.replace(b"\n", b"\r\n")
                )
                self.assert_fails_naming(name)

    def test_invalid_utf8_fails(self) -> None:
        self.baseline()
        self.with_bytes("game/localization/hu.po", lambda data: data + b"\n# \xff\xfe broken\n")
        self.assert_fails_naming("hu.po")

    def test_a_lone_carriage_return_fails(self) -> None:
        self.baseline()
        self.with_bytes("game/localization/en.po", lambda data: data + b"# a\rb\n")
        self.assert_fails_naming("en.po")


