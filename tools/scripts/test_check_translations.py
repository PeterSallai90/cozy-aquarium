"""Tests for check_translations.py, written for issue #18 (localization pipeline).

Each test builds a small repository tree (game/localization/ plus optional sources) in a temporary
directory and calls check(). The baseline tree is valid; a test changes one thing and expects exit
code 1. Assertions use the exit code, the path of the file named on an ERROR line and the offending
key. They never assert the exact wording of an error.

The expected messages.pot is rendered here by a small independent function that follows the
documented output format, so these tests do not import generate_pot.

Run: python -m unittest discover -s tools/scripts -p "test_*.py"
"""

from __future__ import annotations

import contextlib
import io
import subprocess
import sys
import tempfile
import unittest
from collections.abc import Callable
from pathlib import Path

import check_translations

SCRIPT = Path(check_translations.__file__).resolve()
REPO_ROOT = SCRIPT.parents[2]

POT_HEADER = (
    "# Cozy Aquarium translation template. Generated by tools/scripts/generate_pot.py; "
    "do not edit.\n"
    'msgid ""\n'
    'msgstr ""\n'
    '"Project-Id-Version: Cozy Aquarium\\n"\n'
    '"MIME-Version: 1.0\\n"\n'
    '"Content-Type: text/plain; charset=UTF-8\\n"\n'
    '"Content-Transfer-Encoding: 8bit\\n"\n'
)

SINGULAR = "menu.main.new_aquarium"
PLURAL = "fish.count"


def render_pot(entries: dict[str, str | None]) -> str:
    """The documented pot format: sorted by msgid, one blank line between entries, one final LF."""
    text = POT_HEADER
    for msgid in sorted(entries):
        plural = entries[msgid]
        text += f'\nmsgid "{msgid}"\n'
        if plural is None:
            text += 'msgstr ""\n'
        else:
            text += f'msgid_plural "{plural}"\nmsgstr[0] ""\nmsgstr[1] ""\n'
    return text


def po_header(language: str, plural_forms: str = "nplurals=2; plural=(n != 1);") -> str:
    return (
        'msgid ""\n'
        'msgstr ""\n'
        '"Project-Id-Version: Cozy Aquarium\\n"\n'
        f'"Language: {language}\\n"\n'
        '"MIME-Version: 1.0\\n"\n'
        '"Content-Type: text/plain; charset=UTF-8\\n"\n'
        '"Content-Transfer-Encoding: 8bit\\n"\n'
        f'"Plural-Forms: {plural_forms}\\n"\n'
    )


def singular(msgid: str, msgstr: str) -> str:
    return f'\nmsgid "{msgid}"\nmsgstr "{msgstr}"\n'


def plural_entry(msgid: str, plural: str, one: str, many: str) -> str:
    return (
        f'\nmsgid "{msgid}"\nmsgid_plural "{plural}"\n'
        f'msgstr[0] "{one}"\nmsgstr[1] "{many}"\n'
    )


EN_BODY = singular(SINGULAR, "New aquarium") + plural_entry(
    PLURAL, PLURAL + ".plural", "%d fish", "%d fishes"
)
HU_BODY = singular(SINGULAR, "Új akvárium") + plural_entry(
    PLURAL, PLURAL + ".plural", "%d hal", "%d hal"
)


class CheckTranslationsTestBase(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root: Path = Path(tmp.name)
        (self.root / "game" / "localization").mkdir(parents=True)

    # --- helpers -------------------------------------------------------------------------

    def write(self, rel: str, text: str) -> None:
        """Write a UTF-8 file with LF endings, whatever the platform."""
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))

    def write_raw(self, rel: str, data: bytes) -> None:
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def baseline(self) -> None:
        """A valid repository: one singular and one plural key, kept in the pot by extra_keys."""
        self.write(
            "game/localization/extra_keys.txt",
            f"# keys that exist only at run time\n{SINGULAR}\n{PLURAL} {PLURAL}.plural\n",
        )
        self.write(
            "game/localization/messages.pot",
            render_pot({SINGULAR: None, PLURAL: PLURAL + ".plural"}),
        )
        self.write("game/localization/en.po", po_header("en") + EN_BODY)
        self.write("game/localization/hu.po", po_header("hu") + HU_BODY)

    def empty_catalog(self) -> None:
        self.write("game/localization/extra_keys.txt", "# no keys yet\n")
        self.write("game/localization/messages.pot", render_pot({}))
        self.write("game/localization/en.po", po_header("en"))
        self.write("game/localization/hu.po", po_header("hu"))

    def run_check(self) -> tuple[int, list[str]]:
        out = io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
            code = check_translations.check(self.root)
        return code, out.getvalue().splitlines()

    def error_lines(self, lines: list[str]) -> list[str]:
        return [line for line in lines if line.startswith("ERROR")]

    def assert_fails_naming(self, file_name: str, key: str | None = None) -> list[str]:
        code, lines = self.run_check()
        self.assertEqual(code, 1, lines)
        errors = self.error_lines(lines)
        self.assertTrue(any(file_name in line for line in errors), lines)
        if key is not None:
            self.assertIn(key, "\n".join(lines))
        return lines

    def assert_passes(self) -> list[str]:
        code, lines = self.run_check()
        self.assertEqual(code, 0, lines)
        self.assertEqual(self.error_lines(lines), [], lines)
        return lines

    def edit(self, rel: str, old: str, new: str) -> None:
        path = self.root / rel
        text = path.read_text(encoding="utf-8")
        self.assertIn(old, text)
        self.write(rel, text.replace(old, new, 1))


class ConstantsAndKeyRuleTest(unittest.TestCase):
    def test_allowed_areas_are_the_documented_list(self) -> None:
        self.assertEqual(
            tuple(check_translations.ALLOWED_AREAS),
            (
                "menu",
                "save",
                "settings",
                "language",
                "tank",
                "fish",
                "item",
                "ui",
                "photo",
                "datetime",
                "number",
                "unit",
            ),
        )

    def test_plural_constants(self) -> None:
        self.assertEqual(check_translations.PLURAL_SUFFIX, ".plural")
        self.assertEqual(check_translations.PLURAL_FORMS, "nplurals=2; plural=(n != 1);")

    def test_the_same_area_list_is_written_in_the_architecture_doc(self) -> None:
        doc = (REPO_ROOT / "docs" / "architecture.md").read_text(encoding="utf-8")
        for area in check_translations.ALLOWED_AREAS:
            self.assertIn(f"`{area}`", doc, area)

    def test_valid_keys_have_no_error(self) -> None:
        keys = [
            "save.error.not_found",
            "menu.main.new_aquarium",
            "fish.neon_tetra.name",
            "fish.count",
            "ui.fixture.apples",
            "datetime.x",
            "number.x1",
            "unit.cm",
            "photo.date",
            "tank.size.medium",
            "item.rock_a.name",
            "settings.language.label",
            "language.name.en",
        ]
        for area in check_translations.ALLOWED_AREAS:
            keys.append(f"{area}.subject")
        for key in keys:
            with self.subTest(key=key):
                self.assertIsNone(check_translations.key_error(key))

    def test_invalid_keys_have_a_reason(self) -> None:
        keys = [
            "Menu.x",  # upper case
            "menu.Main",
            "menu",  # one segment
            "",
            "menu..x",  # empty segment
            "menu.x.",  # trailing dot
            ".menu.x",  # leading dot
            "menu.x-y",  # dash
            "menu.x y",  # space
            "menu.x\n",  # newline (must not slip through a $ anchor)
            "menu.árvíz",  # non-ASCII
            "foo.bar",  # unknown area
            "Fish.count",
            "menu.x.plural",  # reserved last segment
            "fish.count.plural",
        ]
        for key in keys:
            with self.subTest(key=key):
                reason = check_translations.key_error(key)
                self.assertIsInstance(reason, str)
                self.assertTrue(reason)


