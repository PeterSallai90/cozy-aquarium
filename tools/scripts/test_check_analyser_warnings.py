def load_guard() -> ModuleType:
    return importlib.import_module("check_analyser_warnings")


def warning_block(message: str, path: str, line: int) -> str:
    """A warning as Godot prints it for a script that was loaded with warnings as errors."""
    return (
        f"{ENGINE_PREFIX}{message} (Warning treated as error.)\n"
        f"   at: GDScript::reload ({path}:{line})\n"
    )


def census_output(*blocks: str, scripts: int = 3, failing: int = 0) -> str:
    done = f"CENSUS_DONE scripts={scripts} failing={failing}\n"
    return "Godot Engine v4.7.2.stable.official\n\n" + "".join(blocks) + done


def probe_output(*rows: tuple[str, int, int]) -> str:
    lines = [f"CODE {code} {project} {default}" for code, project, default in rows]
    return "\n".join([*lines, "PROBE_DONE"]) + "\n"


class AnalyserGuardTest(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)
        self.game = self.root / "game"
        self.game.mkdir()

    def make_imported(self) -> None:
        (self.game / ".godot" / "imported").mkdir(parents=True)
        (self.game / ".godot" / "global_script_class_cache.cfg").write_text("", encoding="utf-8")

    def run_main(self, env: dict[str, str]) -> tuple[int, str]:
        guard = load_guard()
        out = io.StringIO()
        err = io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code: int = guard.main(["--project", str(self.game)], env)
        return code, out.getvalue() + err.getvalue()

    # Binary lookup (B7, B7a)

    def test_godot_env_pointing_to_a_missing_file_exits_2_naming_the_path(self) -> None:
        missing = str(self.root / "no-such-godot")
        code, output = self.run_main({"GODOT": missing})
        self.assertEqual(code, 2)
        self.assertIn("Godot not runnable: GODOT=" + missing, output)

    def test_no_binary_on_path_exits_2_with_the_exact_message(self) -> None:
        guard = load_guard()
        with self.assertRaises(guard.SetupError) as raised:
            guard.find_godot({}, lambda _name: None)
        self.assertEqual(
            str(raised.exception),
            "Godot not found: put godot_console or godot on PATH or set GODOT",
        )

    def test_lookup_order_is_godot_env_then_godot_console_then_godot(self) -> None:
        guard = load_guard()
        asked: list[str] = []

        def which_only_godot(name: str) -> str | None:
            asked.append(name)
            return "/usr/bin/godot" if name == "godot" else None

        self.assertEqual(guard.find_godot({}, which_only_godot), "/usr/bin/godot")
        self.assertEqual(asked, ["godot_console", "godot"])

        asked.clear()

        def which_both(name: str) -> str | None:
            asked.append(name)
            return "/usr/bin/" + name

        self.assertEqual(guard.find_godot({}, which_both), "/usr/bin/godot_console")
        self.assertEqual(asked, ["godot_console"])

        # GODOT wins and is never combined with a fallback (sys.executable runs --version).
        asked.clear()
        self.assertEqual(guard.find_godot({"GODOT": sys.executable}, which_both), sys.executable)
        self.assertEqual(asked, [])

    # Import check

    def test_missing_import_cache_exits_2_with_the_exact_message(self) -> None:
        expected = "Project not imported: run godot_console --headless --path game --import"
        guard = load_guard()
        with self.assertRaises(guard.SetupError) as raised:
            guard.check_imported(self.game)
        self.assertEqual(str(raised.exception), expected)
        code, output = self.run_main({"GODOT": sys.executable})
        self.assertEqual(code, 2)
        self.assertIn(expected, output)

    # Census result

    def test_missing_census_result_line_exits_2(self) -> None:
        guard = load_guard()
        crashed = "Godot Engine v4.7.2\n" + warning_block(DIVISION_TEXT, "res://a.gd", 5)
        with self.assertRaises(guard.SetupError):
            guard.parse_census(crashed)
        with self.assertRaises(guard.SetupError):
            guard.parse_census("CENSUS_DONE scripts=many failing=x\n")

    def test_zero_scripts_exits_2(self) -> None:
        guard = load_guard()
        with self.assertRaises(guard.SetupError):
            guard.parse_census(census_output(scripts=0, failing=0))

    def test_clean_parsed_result_exits_0(self) -> None:
        guard = load_guard()
        result = guard.parse_census(census_output(scripts=267, failing=0))
        self.assertEqual(result.scripts, 267)
        self.assertEqual(len(result.failing_paths), 0)
        self.assertEqual(len(result.findings), 0)
        self.assertEqual((guard.EXIT_CLEAN, guard.EXIT_FINDINGS, guard.EXIT_SETUP), (0, 1, 2))

    def test_findings_name_path_line_and_code(self) -> None:
        guard = load_guard()
        output = census_output(
            warning_block(SAMPLES["integer_division"], "res://model/a.gd", 5),
            warning_block(SAMPLES["redundant_await"], "res://tests/test_b.gd", 17),
            "CENSUS_FAIL res://model/a.gd\n",
            scripts=10,
            failing=1,
        )
        found = {
            (f.path.removeprefix("res://"), f.line, f.code)
            for f in guard.parse_census(output).findings
        }
        self.assertEqual(
            found,
            {
                ("model/a.gd", 5, "integer_division"),
                ("tests/test_b.gd", 17, "redundant_await"),
            },
        )

    def test_paths_under_addons_godot_and_guard_folders_are_ignored(self) -> None:
        guard = load_guard()
        output = census_output(
            warning_block(DIVISION_TEXT, "res://addons/gdUnit4/x.gd", 1),
            warning_block(DIVISION_TEXT, "res://.godot/y.gd", 2),
            warning_block(DIVISION_TEXT, "res://_analyser_guard_selftest_1_ab12/bad.gd", 5),
            warning_block(DIVISION_TEXT, "res://_analyser_guard_7_cd34/z.gd", 6),
            warning_block(DIVISION_TEXT, "res://scenes/real.gd", 9),
        )
        findings = guard.parse_census(output).findings
        self.assertEqual([(f.path, f.line) for f in findings], [("res://scenes/real.gd", 9)])

    def test_unmatched_message_is_a_finding_with_code_unknown(self) -> None:
        guard = load_guard()
        text = "A brand new analyser message nobody wrote a pattern for."
        output = census_output(warning_block(text, "res://scenes/new.gd", 3))
        findings = guard.parse_census(output).findings
        self.assertEqual(len(findings), 1)
        self.assertEqual(findings[0].code, "unknown")
        self.assertIn(text, findings[0].message)

    # Drift (B9)

    def test_engine_code_missing_from_the_table_is_a_drift_finding_naming_the_code(self) -> None:
        guard = load_guard()
        levels = guard.parse_probe(
            probe_output(("integer_division", 1, 1), ("brand_new_code", 1, 1), ("off_code", 0, 0))
        )
        self.assertEqual(levels["brand_new_code"], (1, 1))
        lines = guard.check_drift(levels, {"integer_division": ".+"}, {})
        self.assertTrue(
            any("analyser code not covered by the guard: brand_new_code" in x for x in lines),
            lines,
        )
        self.assertFalse(any("integer_division" in x for x in lines), lines)
        self.assertFalse(any("off_code" in x for x in lines), lines)
        # A code listed with a reason in the excluded table is covered.
        covered = guard.check_drift(levels, {"integer_division": ".+"}, {"brand_new_code": "why"})
        self.assertFalse(any("brand_new_code" in x for x in covered), covered)

    def test_table_code_unknown_to_the_engine_is_a_drift_finding_naming_the_code(self) -> None:
        guard = load_guard()
        levels = guard.parse_probe(probe_output(("integer_division", 1, 1)))
        lines = guard.check_drift(
            levels, {"integer_division": ".+", "ghost_code": ".+"}, {"ghost_excluded": "why"}
        )
        self.assertTrue(
            any("guard code unknown to the engine: ghost_code" in x for x in lines), lines
        )
        self.assertTrue(
            any("guard code unknown to the engine: ghost_excluded" in x for x in lines), lines
        )
        self.assertFalse(any("integer_division" in x for x in lines), lines)

    # Foreign override.cfg

    def test_foreign_override_cfg_exits_2_and_is_left_in_place(self) -> None:
        self.make_imported()
        override = self.game / "override.cfg"
        content = "[debug]\n\ngdscript/warnings/integer_division=0\n"
        override.write_text(content, encoding="utf-8")
        code, output = self.run_main({"GODOT": sys.executable})
        self.assertEqual(code, 2)
        self.assertIn("override.cfg", output)
        self.assertTrue(override.is_file())
        self.assertEqual(override.read_text(encoding="utf-8"), content)
        self.assertNotEqual(content.splitlines()[0], MARKER)

    # Message table

    def test_each_message_pattern_matches_its_own_sample_and_no_other(self) -> None:
        guard = load_guard()
        table: dict[str, str] = guard.MESSAGES
        for code in ("integer_division", "redundant_await", "incompatible_ternary"):
            self.assertIn(code, table)
        for code in ("shadowed_variable_base_class", "unused_signal"):
            self.assertIn(code, table)
        self.assertEqual(len(set(table.values())), len(table), "two codes share one pattern")
        for code, sample in SAMPLES.items():
            self.assertIn(code, table, f"no pattern for {code}")
            for other, pattern in table.items():
                matched = re.fullmatch(pattern, sample) is not None
                self.assertEqual(matched, other == code, f"{other} against the {code} sample")

    def test_census_root_drops_findings_and_failures_outside_the_folder(self) -> None:
        guard = load_guard()
        root = "res://scratch_case/"
        output = census_output(
            warning_block(DIVISION_TEXT, "res://model/command.gd", 16),
            warning_block(DIVISION_TEXT, root + "case.gd", 4),
            "CENSUS_FAIL res://model/command.gd\n",
            "CENSUS_FAIL " + root + "case.gd\n",
            failing=2,
        )
        result = guard.parse_census(output, keep_prefix=root)
        self.assertEqual([(f.path, f.line) for f in result.findings], [(root + "case.gd", 4)])
        self.assertEqual(result.failing_paths, [root + "case.gd"])

    def test_census_without_root_keeps_tree_findings_and_excludes_addons(self) -> None:
        guard = load_guard()
        output = census_output(
            warning_block(DIVISION_TEXT, "res://model/command.gd", 16),
            warning_block(DIVISION_TEXT, "res://addons/x/y.gd", 2),
            "CENSUS_FAIL res://model/command.gd\n",
            failing=1,
        )
        result = guard.parse_census(output)
        self.assertEqual(
            [(f.path, f.line) for f in result.findings], [("res://model/command.gd", 16)],
        )
        self.assertEqual(result.failing_paths, ["res://model/command.gd"])


