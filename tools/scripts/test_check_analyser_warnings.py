"""Tests for issue #148: the analyser warning guard (tools/scripts/check_analyser_warnings.py).

Pure Python, no Godot: fake `which`, fake environments, a temporary project directory and canned
Godot output. The 14 cases follow the technical plan, section 5. The Godot-backed behaviour
(four self-test cases inside the guard, planted warnings, timing) is checked manually.

The guard module is imported lazily so that a missing script fails these tests only.

Run: python -m unittest discover -s tools/scripts -p "test_*.py"
"""

