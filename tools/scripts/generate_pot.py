"""Generate game/localization/messages.pot from the translation keys used by the game.

Sources (paths relative to game/; the top-level tests/, addons/, .godot/ and reports/ are skipped):
1. **/*.gd: the first argument of tr(), tr_n(), atr() and atr_n() calls.
2. **/*.tscn: the text, tooltip_text, placeholder_text and title properties of nodes.
3. catalog/**/*.tres: every <name>_key property.
4. localization/extra_keys.txt: keys that exist only at run time ("key" or "key key.plural").

Exit code 0 when the pot was written (or is up to date with --check); 1 on source errors, or with
--check when the pot is stale. Output is byte-identical on every platform.

Usage: python tools/scripts/generate_pot.py [--root REPO_ROOT] [--check]
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path

from check_translations import PLURAL_SUFFIX, key_error

POT_PATH = Path("game/localization/messages.pot")
SCRIPT_PATH = "tools/scripts/generate_pot.py"
EXTRA_KEYS_PATH = Path("localization/extra_keys.txt")
SKIPPED_TOP_LEVEL = frozenset({"tests", "addons", ".godot", "reports"})
CALLS = frozenset({"tr", "tr_n", "atr", "atr_n"})
TSCN_PROPERTY = re.compile(r"(?:text|tooltip_text|placeholder_text|title) = (.*)")
TRES_KEY_PROPERTY = re.compile(r"\w*_key = (.*)")
QUOTED_PLAIN = re.compile(r'"([^"\\\n]*)"')
IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
NUMBER = re.compile(r"[0-9][0-9_.xXa-fA-F]*")

POT_HEADER = (
    "# Cozy Aquarium translation template. Generated by tools/scripts/generate_pot.py; "
    "do not edit.\n"
    'msgid ""\n'
    'msgstr ""\n'
    '"Project-Id-Version: Cozy Aquarium\\n"\n'
    '"MIME-Version: 1.0\\n"\n'
    '"Content-Type: text/plain; charset=UTF-8\\n"\n'
    '"Content-Transfer-Encoding: 8bit\\n"\n'
)

Entries = dict[str, str | None]  # msgid -> msgid_plural or None


@dataclass(frozen=True)
class Token:
    """A GDScript token: kind is str, id, num or p (punctuation); prefix is r, & or ^ on a str."""

    kind: str
    text: str
    line: int
    prefix: str = ""


def tokenize(source: str) -> list[Token]:
    """Split GDScript source into tokens, skipping comments and whitespace."""
    tokens: list[Token] = []
    i = 0
    line = 1
    end = len(source)
    while i < end:
        char = source[i]
        if char == "\n":
            line += 1
            i += 1
        elif char in " \t\r":
            i += 1
        elif char == "#":
            while i < end and source[i] != "\n":
                i += 1
        elif char in "\"'" or (char in "r&^" and source[i + 1 : i + 2] in ('"', "'")):
            prefix = char if char in "r&^" else ""
            start = i + len(prefix)
            text, i, newlines = _read_string(source, start)
            tokens.append(Token("str", text, line, prefix))
            line += newlines
        elif match := IDENTIFIER.match(source, i):
            tokens.append(Token("id", match.group(0), line))
            i = match.end()
        elif match := NUMBER.match(source, i):
            tokens.append(Token("num", match.group(0), line))
            i = match.end()
        else:
            tokens.append(Token("p", char, line))
            i += 1
    return tokens


def _read_string(source: str, start: int) -> tuple[str, int, int]:
    """Read the string literal whose opening quote is at `start`.

    Returns (raw text without quotes, index after the literal, newlines inside).
    """
    quote = source[start]
    triple = source.startswith(quote * 3, start)
    index = start + (3 if triple else 1)
    body_start = index
    newlines = 0
    while index < len(source):
        char = source[index]
        if char == "\\":
            if source[index + 1 : index + 2] == "\n":
                newlines += 1
            index += 2
            continue
        if triple and source.startswith(quote * 3, index):
            return source[body_start:index], index + 3, newlines
        if not triple and (char == quote or char == "\n"):
            return source[body_start:index], index + 1, newlines
        if char == "\n":
            newlines += 1
        index += 1
    return source[body_start:], len(source), newlines


def split_arguments(tokens: list[Token], open_index: int) -> list[list[Token]]:
    """Return the top-level arguments of the call whose "(" is at `open_index`."""
    arguments: list[list[Token]] = [[]]
    depth = 0
    for token in tokens[open_index:]:
        if token.kind == "p" and token.text in "([{":
            depth += 1
            if depth == 1:
                continue
        elif token.kind == "p" and token.text in ")]}":
            depth -= 1
            if depth == 0:
                break
        elif token.kind == "p" and token.text == "," and depth == 1:
            arguments.append([])
            continue
        arguments[-1].append(token)
    if arguments[-1] == []:
        arguments.pop()
    return arguments


def expression_text(tokens: list[Token]) -> str:
    return "".join(f'"{t.text}"' if t.kind == "str" else t.text for t in tokens)


def is_key_expression(tokens: list[Token]) -> bool:
    """True for an identifier or dotted member access whose last name is key or *_key."""
    if len(tokens) % 2 == 0:
        return False
    for index, token in enumerate(tokens):
        if index % 2 == 0 and token.kind != "id":
            return False
        if index % 2 == 1 and token.text != ".":
            return False
    last = tokens[-1].text
    return last == "key" or last.endswith("_key")


def _is_plain_literal(tokens: list[Token]) -> bool:
    return len(tokens) == 1 and tokens[0].kind == "str" and tokens[0].prefix == ""


def _add(entries: Entries, key: str, plural: str | None, errors: list[str], where: str) -> None:
    if key in entries and entries[key] != plural:
        errors.append(f"{where}: key {key} is used both as singular and as plural")
    else:
        entries[key] = plural


def _scan_call(
    tokens: list[Token], index: int, rel: str, entries: Entries, errors: list[str]
) -> None:
    """Check one tr()-style call; `index` is the position of its function name."""
    name = tokens[index]
    where = f"{rel}:{name.line}"
    plural = name.text.endswith("_n")
    arguments = split_arguments(tokens, index + 1)
    if len(arguments) != (3 if plural else 1):
        errors.append(
            f"{where}: {name.text}() has the wrong argument count (msgctxt is not allowed)"
        )
        return
    first = arguments[0]
    if _is_plain_literal(first):
        key = first[0].text
        reason = key_error(key)
        if reason:
            errors.append(f"{where}: bad key {key}: {reason}")
            return
        plural_key: str | None = None
        if plural:
            second = arguments[1]
            if not (_is_plain_literal(second) and second[0].text == key + PLURAL_SUFFIX):
                errors.append(f'{where}: the second argument must be the literal "{key}.plural"')
                return
            plural_key = key + PLURAL_SUFFIX
        _add(entries, key, plural_key, errors, where)
    elif is_key_expression(first):
        expected = expression_text(first) + '+".plural"'
        if plural and expression_text(arguments[1]) != expected:
            errors.append(
                f'{where}: the second argument must be {expression_text(first)} + ".plural"'
            )
    else:
        errors.append(
            f"{where}: non-literal key; use a literal or a variable named key or ending in _key"
        )


def scan_gd(path: Path, rel: str, entries: Entries, errors: list[str]) -> None:
    tokens = tokenize(path.read_text(encoding="utf-8"))
    for index, token in enumerate(tokens):
        if token.kind != "id" or token.text not in CALLS:
            continue
        following = tokens[index + 1] if index + 1 < len(tokens) else None
        if following is None or following.kind != "p" or following.text != "(":
            continue
        if index > 0 and tokens[index - 1].kind == "id" and tokens[index - 1].text == "func":
            continue
        _scan_call(tokens, index, rel, entries, errors)


def scan_tscn(path: Path, rel: str, entries: Entries, errors: list[str]) -> None:
    in_node = False
    for number, line in enumerate(path.read_text(encoding="utf-8").split("\n"), start=1):
        if line.startswith("["):
            in_node = line.startswith("[node")
            continue
        match = TSCN_PROPERTY.fullmatch(line) if in_node else None
        if match is None or match.group(1) == '""':
            continue
        quoted = QUOTED_PLAIN.fullmatch(match.group(1))
        if quoted is None or key_error(quoted.group(1)):
            errors.append(f"{rel}:{number}: this text property is not a valid translation key")
        else:
            _add(entries, quoted.group(1), None, errors, f"{rel}:{number}")


def scan_tres(path: Path, rel: str, entries: Entries, errors: list[str]) -> None:
    for number, line in enumerate(path.read_text(encoding="utf-8").split("\n"), start=1):
        match = TRES_KEY_PROPERTY.fullmatch(line)
        if match is None or match.group(1) == '""':
            continue
        quoted = QUOTED_PLAIN.fullmatch(match.group(1))
        if quoted is None or key_error(quoted.group(1)):
            errors.append(f"{rel}:{number}: this *_key property is not a valid translation key")
        else:
            _add(entries, quoted.group(1), None, errors, f"{rel}:{number}")


def scan_extra_keys(path: Path, rel: str, entries: Entries, errors: list[str]) -> None:
    for number, line in enumerate(path.read_text(encoding="utf-8").split("\n"), start=1):
        text = line.strip()
        if not text or text.startswith("#"):
            continue
        parts = text.split(" ")
        where = f"{rel}:{number}"
        if len(parts) > 2:
            errors.append(f"{where}: expected 'key' or 'key key.plural'")
        elif key_error(parts[0]):
            errors.append(f"{where}: bad key {parts[0]}: {key_error(parts[0])}")
        elif len(parts) == 2 and parts[1] != parts[0] + PLURAL_SUFFIX:
            errors.append(f"{where}: the plural must be '{parts[0]}{PLURAL_SUFFIX}'")
        else:
            _add(entries, parts[0], parts[1] if len(parts) == 2 else None, errors, where)


def _source_files(game: Path) -> Iterator[Path]:
    for path in sorted(game.iterdir()):
        if path.is_dir():
            if path.name not in SKIPPED_TOP_LEVEL:
                yield from sorted(p for p in path.rglob("*") if p.is_file())
        else:
            yield path


def collect(root: Path) -> tuple[Entries, list[str]]:
    """Collect every key. Returns (msgid -> msgid_plural or None, errors as "path:line: text")."""
    game = root / "game"
    entries: Entries = {}
    errors: list[str] = []
    if not game.is_dir():
        return entries, errors
    for path in _source_files(game):
        rel = path.relative_to(root).as_posix()
        if path.suffix == ".gd":
            scan_gd(path, rel, entries, errors)
        elif path.suffix == ".tscn":
            scan_tscn(path, rel, entries, errors)
        elif path.suffix == ".tres" and path.relative_to(game).parts[0] == "catalog":
            scan_tres(path, rel, entries, errors)
    extra = game / EXTRA_KEYS_PATH
    if extra.is_file():
        scan_extra_keys(extra, extra.relative_to(root).as_posix(), entries, errors)
    return entries, sorted(errors)


def render_pot(entries: Entries) -> str:
    """Render the template: entries sorted by msgid, one blank line between them."""
    text = POT_HEADER
    for key in sorted(entries):
        plural = entries[key]
        text += f'\nmsgid "{key}"\n'
        if plural is None:
            text += 'msgstr ""\n'
        else:
            text += f'msgid_plural "{plural}"\nmsgstr[0] ""\nmsgstr[1] ""\n'
    return text


def check(root: Path, write: bool) -> int:
    """Write the pot (write=True) or verify it is current. Returns the exit code."""
    entries, errors = collect(root)
    if errors:
        for message in errors:
            print(f"ERROR: {message}")
        return 1
    data = render_pot(entries).encode("utf-8")
    pot = root / POT_PATH
    if write:
        pot.parent.mkdir(parents=True, exist_ok=True)
        pot.write_bytes(data)
        return 0
    if not pot.is_file() or pot.read_bytes() != data:
        print(f"ERROR: {POT_PATH.as_posix()} is out of date; run python {SCRIPT_PATH}")
        return 1
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--check", action="store_true", help="exit 1 if the pot is stale")
    args = parser.parse_args()
    return check(args.root.resolve(), write=not args.check)


if __name__ == "__main__":
    sys.exit(main())
