def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Fail on any GDScript analyser warning.")
    parser.add_argument("--project", type=Path, default=REPO_ROOT / "game")
    parser.add_argument("--only", default="", help="census root (used by the self-test)")
    parser.add_argument("--drop-code", default="", help="self-test only")
    return parser


def _run(args: argparse.Namespace, env: Mapping[str, str]) -> int:
    game_dir: Path = args.project
    is_child = env.get(CHILD_VARIABLE) == "1"
    if args.drop_code and not is_child:
        raise SetupError(f"--drop-code is only allowed with {CHILD_VARIABLE}=1")

    godot = find_godot(env, shutil.which)
    check_imported(game_dir)
    if not is_child:
        stale_cleanup(game_dir)
        self_test(godot, game_dir)

    run_name = f"{GUARD_PREFIX}_{os.getpid()}_{secrets.token_hex(4)}"
    run_dir = game_dir / run_name
    logs: list[Path] = []
    try:
        run_dir.mkdir()
        write_scene(run_dir, "probe", PROBE_GD)
        output, log = run_godot(godot, game_dir, f"res://{run_name}/probe.tscn", [], "probe")
        logs.append(log)
        levels = parse_probe(output, log)

        messages = {code: p for code, p in MESSAGES.items() if code != args.drop_code}
        drift = check_drift(levels, messages, EXCLUDED)
        raised = sorted(
            code for code, (project, _d) in levels.items() if project == 1 and code not in EXCLUDED
        )

        write_scene(run_dir, "census", CENSUS_GD)
        override = game_dir / "override.cfg"
        override.write_text(override_text(raised), encoding="utf-8", newline="\n")
        extra = ["--", args.only] if args.only else []
        output, log = run_godot(godot, game_dir, f"res://{run_name}/census.tscn", extra, "census")
        logs.append(log)
        remove_override(game_dir)
        result = parse_census(output, messages, args.only, log)
        version = godot_version(godot)
    finally:
        remove_tree(run_dir)
        remove_override(game_dir)
        if run_dir.exists() or (game_dir / "override.cfg").exists():
            raise SetupError("Cleanup failed: generated guard files are still in " + str(game_dir))

    lines = [f.render() for f in result.findings]
    with_findings = {f.path for f in result.findings}
    for path in result.failing_paths:
        if path not in with_findings:
            lines.append(f"{path}: {UNBLOCKED_NOTE}")
    lines.extend(drift)
    warnings = len(result.findings) + len(drift)
    for line in sorted(lines):
        print(line)
    error_count = sum(1 for project, _d in levels.values() if project == 2)
    off_count = sum(1 for project, _d in levels.values() if project == 0)
    print(f"codes: raised={len(raised)} error={error_count} off={off_count} (Godot {version})")
    print(
        f"census: scripts={result.scripts} failing={len(result.failing_paths)} warnings={warnings}"
    )
    for log in logs:
        log.unlink(missing_ok=True)
    if lines:
        return EXIT_FINDINGS
    return EXIT_CLEAN


def main(argv: list[str] | None = None, env: Mapping[str, str] | None = None) -> int:
    environment = os.environ if env is None else env
    args = _build_parser().parse_args(argv)
    try:
        return _run(args, environment)
    except SetupError as error:
        print(str(error))
        return EXIT_SETUP
    except OSError as error:
        print(f"Guard setup failed: {error}")
        return EXIT_SETUP


if __name__ == "__main__":
    sys.exit(main())
