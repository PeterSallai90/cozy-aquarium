class SetupError(Exception):
    """A setup or tool failure; the message is printed and the exit code is 2."""


@dataclass(frozen=True)
class Finding:
    path: str
    line: int
    code: str
    message: str

    def render(self) -> str:
        return f"{self.path}:{self.line}: {self.code}: {self.message}"


@dataclass
class CensusResult:
    scripts: int
    failing_paths: list[str] = field(default_factory=list)
    findings: list[Finding] = field(default_factory=list)


def strip_ansi(text: str) -> str:
    return ANSI.sub("", text)


def _version_runs(binary: str) -> bool:
    try:
        done = subprocess.run(
            [binary, "--version"], capture_output=True, timeout=60, check=False
        )
    except (OSError, subprocess.SubprocessError):
        return False
    return done.returncode == 0


def find_godot(env: Mapping[str, str], which: Callable[[str], str | None]) -> str:
    """GODOT env (must run), then godot_console, then godot."""
    explicit = env.get("GODOT")
    if explicit:
        if not Path(explicit).is_file() or not _version_runs(explicit):
            raise SetupError(f"Godot not runnable: GODOT={explicit}")
        return explicit
    for name in ("godot_console", "godot"):
        found = which(name)
        if found:
            return found
    raise SetupError(NOT_FOUND_MESSAGE)


def check_imported(game_dir: Path) -> None:
    imported = game_dir / ".godot" / "imported"
    cache = game_dir / ".godot" / "global_script_class_cache.cfg"
    if not imported.is_dir() or not cache.is_file():
        raise SetupError(NOT_IMPORTED_MESSAGE)


def _log_note(log: Path | None) -> str:
    """The kept log path and its last lines, for a setup error."""
    if log is None:
        return ""
    return f"; log: {log}\n{_tail(log)}"


def parse_probe(output: str, log: Path | None = None) -> dict[str, tuple[int, int]]:
    """Map each code to (project level, engine default)."""
    text = strip_ansi(output)
    if not re.search(r"^PROBE_DONE\s*$", text, re.MULTILINE):
        raise SetupError("Probe run did not finish: no PROBE_DONE line" + _log_note(log))
    levels: dict[str, tuple[int, int]] = {}
    for match in re.finditer(r"^CODE (\w+) (\d+) (\d+)\s*$", text, re.MULTILINE):
        levels[match.group(1)] = (int(match.group(2)), int(match.group(3)))
    if not levels:
        raise SetupError("Probe run listed no analyser codes")
    return levels


def check_drift(
    levels: Mapping[str, tuple[int, int]],
    messages: Mapping[str, str],
    excluded: Mapping[str, str],
) -> list[str]:
    """Findings for codes the engine knows and the guard does not, or the reverse (B9)."""
    lines: list[str] = []
    required = sorted(
        code for code, (project, default) in levels.items() if max(project, default) > 0
    )
    for code in required:
        if code not in messages and code not in excluded:
            lines.append(f"analyser code not covered by the guard: {code}")
    for code in sorted({*messages, *excluded}):
        if code not in levels:
            lines.append(f"guard code unknown to the engine: {code}")
    for code in required:
        if levels[code][0] == 0:
            lines.append(f"analyser code turned off in game/project.godot: {code}")
    return lines


def _ignored_path(path: str, keep_prefix: str) -> bool:
    if keep_prefix and path.startswith(keep_prefix):
        return False
    return path.startswith(EXCLUDED_PREFIXES)


def classify(message: str, messages: Mapping[str, str]) -> str:
    for code, pattern in messages.items():
        if re.fullmatch(pattern, message):
            return code
    return "unknown"


def parse_census(
    output: str,
    messages: Mapping[str, str] | None = None,
    keep_prefix: str = "",
    log: Path | None = None,
) -> CensusResult:
    """Parse the census output. `keep_prefix` is the self-test folder, which is not dropped."""
    table = MESSAGES if messages is None else messages
    lines = strip_ansi(output).splitlines()
    done: re.Match[str] | None = None
    for line in lines:
        found = re.fullmatch(r"\s*CENSUS_DONE scripts=(\d+) failing=(\d+)\s*", line)
        if found:
            done = found
    if done is None:
        raise SetupError("Census did not finish: no CENSUS_DONE result line" + _log_note(log))
    scripts = int(done.group(1))
    if scripts == 0:
        raise SetupError("Census loaded no scripts (scripts=0)")
    result = CensusResult(scripts=scripts)
    seen: set[tuple[str, int, str]] = set()
    for index, line in enumerate(lines):
        fail = re.fullmatch(r"\s*CENSUS_FAIL (res://\S+)\s*", line)
        if fail:
            result.failing_paths.append(fail.group(1))
            continue
        warned = re.search(r"Parse Error: (.+) \(Warning treated as error\.\)\s*$", line)
        if not warned:
            continue
        message = warned.group(1)
        location = None
        for follow in lines[index + 1 : index + 4]:
            location = re.search(r"at: GDScript::reload \((res://.+?):(\d+)\)", follow)
            if location:
                break
        path = location.group(1) if location else "res://?"
        number = int(location.group(2)) if location else 0
        if _ignored_path(path, keep_prefix):
            continue
        key = (path, number, message)
        if key in seen:
            continue
        seen.add(key)
        result.findings.append(Finding(path, number, classify(message, table), message))
    result.findings.sort(key=lambda f: (f.path, f.line, f.message))
    result.failing_paths = sorted(set(result.failing_paths))
    return result


