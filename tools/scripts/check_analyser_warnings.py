CENSUS_GD = """extends Node

const SKIPPED: PackedStringArray = ["res://addons", "res://.godot"]
const GUARD_PREFIX: String = "_analyser_guard"


func _ready() -> void:
	var start: String = "res://"
	var args: PackedStringArray = OS.get_cmdline_user_args()
	if args.size() > 0:
		start = args[0]
	var paths: PackedStringArray = []
	_collect(start, paths)
	paths.sort()
	var failing: int = 0
	for path: String in paths:
		var loaded: GDScript = (
			ResourceLoader.load(path, "", ResourceLoader.CACHE_MODE_IGNORE) as GDScript
		)
		if loaded == null or not loaded.can_instantiate():
			failing += 1
			print("CENSUS_FAIL %s" % path)
	print("CENSUS_DONE scripts=%d failing=%d" % [paths.size(), failing])
	get_tree().quit()


func _collect(dir_path: String, paths: PackedStringArray) -> void:
	for file_name: String in DirAccess.get_files_at(dir_path):
		if file_name.ends_with(".gd"):
			paths.append(dir_path.path_join(file_name))
	for dir_name: String in DirAccess.get_directories_at(dir_path):
		var child: String = dir_path.path_join(dir_name)
		if SKIPPED.has(child) or dir_name.begins_with(GUARD_PREFIX):
			continue
		_collect(child, paths)
"""


def scene_text(script_name: str, run_dir_name: str) -> str:
    return (
        "[gd_scene format=3]\n\n"
        f'[ext_resource type="Script" path="res://{run_dir_name}/{script_name}" id="1"]\n\n'
        '[node name="Guard" type="Node"]\n'
        'script = ExtResource("1")\n'
    )


def write_scene(run_dir: Path, name: str, script_text: str) -> None:
    (run_dir / f"{name}.gd").write_text(script_text, encoding="utf-8", newline="\n")
    (run_dir / f"{name}.tscn").write_text(
        scene_text(f"{name}.gd", run_dir.name), encoding="utf-8", newline="\n"
    )


def override_text(codes: list[str]) -> str:
    body = "".join(f"gdscript/warnings/{code}=2\n" for code in codes)
    return f"{MARKER}\n[debug]\n\n{body}"


# Godot runs --------------------------------------------------------------------------------


def _tail(path: Path, count: int = 20) -> str:
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return ""
    return "\n".join(lines[-count:])


def run_godot(
    godot: str, game_dir: Path, scene: str, extra: list[str], tag: str
) -> tuple[str, Path]:
    """Run a scene headless. Returns (output, log path). Raises SetupError on crash or timeout."""
    log_name = f"analyser_guard_{tag}_{os.getpid()}_{secrets.token_hex(4)}.log"
    log = Path(tempfile.gettempdir()) / log_name
    command = [godot, "--headless", "--path", str(game_dir), scene, *extra]
    try:
        with log.open("wb") as handle:
            done = subprocess.run(
                command,
                stdout=handle,
                stderr=subprocess.STDOUT,
                timeout=GODOT_TIMEOUT_SECONDS,
                check=False,
            )
    except subprocess.TimeoutExpired as error:
        raise SetupError(
            f"Godot timed out after {GODOT_TIMEOUT_SECONDS} s ({tag}); log: {log}"
        ) from error
    except OSError as error:
        raise SetupError(f"Godot could not be started: {error}") from error
    output = log.read_text(encoding="utf-8", errors="replace")
    if done.returncode != 0:
        raise SetupError(
            f"Godot exited with code {done.returncode} ({tag}); log: {log}\n{_tail(log)}"
        )
    return output, log


def godot_version(godot: str) -> str:
    try:
        done = subprocess.run([godot, "--version"], capture_output=True, timeout=60, check=False)
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    text = done.stdout.decode("utf-8", errors="replace").strip()
    return text.splitlines()[0] if text else "unknown"


def remove_tree(path: Path) -> None:
    if path.is_dir():
        shutil.rmtree(path, ignore_errors=True)


def remove_override(game_dir: Path) -> None:
    override = game_dir / "override.cfg"
    if override.is_file():
        first = override.read_text(encoding="utf-8", errors="replace").splitlines()[:1]
        if first == [MARKER]:
            override.unlink()


def stale_cleanup(game_dir: Path) -> None:
    for folder in game_dir.glob(GUARD_PREFIX + "*"):
        remove_tree(folder)
    override = game_dir / "override.cfg"
    if override.is_file():
        first = override.read_text(encoding="utf-8", errors="replace").splitlines()[:1]
        if first != [MARKER]:
            raise SetupError(
                f"Foreign {override} found: it is not generated by this guard. Move or delete it"
                " and run the guard again."
            )
        override.unlink()


# Self-test (B8) ----------------------------------------------------------------------------

BAD_GD = "extends RefCounted\n\n\nfunc f(a: int) -> int:\n\treturn a / 2\n"
CLEAN_GD = "extends RefCounted\n\n\nfunc f(a: int) -> int:\n\treturn a + 1\n"


def _child(
    godot: str, game_dir: Path, extra: list[str], env_extra: dict[str, str]
) -> tuple[int, str]:
    env = dict(os.environ)
    env.update({"GODOT": godot, CHILD_VARIABLE: "1"})
    env.update(env_extra)
    try:
        done = subprocess.run(
            [sys.executable, str(SELF_PATH), "--project", str(game_dir), *extra],
            capture_output=True,
            env=env,
            timeout=GODOT_TIMEOUT_SECONDS * 2,
            check=False,
        )
    except subprocess.TimeoutExpired as error:
        raise SetupError(
            f"analyser guard self-test timed out after {GODOT_TIMEOUT_SECONDS * 2} s"
        ) from error
    stdout = done.stdout.decode("utf-8", errors="replace")
    text = stdout + done.stderr.decode("utf-8", errors="replace")
    return done.returncode, text


def self_test(godot: str, game_dir: Path) -> None:
    folder = f"{GUARD_PREFIX}_selftest_{os.getpid()}_{secrets.token_hex(4)}"
    path = game_dir / folder
    only = f"res://{folder}/"
    path.mkdir()
    try:
        (path / "bad.gd").write_text(BAD_GD, encoding="utf-8", newline="\n")
        (path / "clean.gd").write_text(CLEAN_GD, encoding="utf-8", newline="\n")
        cases: list[tuple[str, int, list[str]]] = []

        code, text = _child(godot, game_dir, ["--only", only], {})
        expected = f"{only}bad.gd:5: integer_division:"
        if code != EXIT_FINDINGS or expected not in text or "clean.gd" in text:
            cases.append(("S1 planted integer division is found", code, [text]))
        (path / "bad.gd").unlink()

        code, text = _child(godot, game_dir, ["--only", only], {})
        if code != EXIT_CLEAN or text.strip().splitlines()[-1:] != [
            "census: scripts=1 failing=0 warnings=0"
        ]:
            cases.append(("S2 clean file passes", code, [text]))

        missing = str(path / "no-such-godot")
        code, text = _child(godot, game_dir, ["--only", only], {"GODOT": missing})
        if code != EXIT_SETUP or missing not in text:
            cases.append(("S3 missing GODOT exits 2", code, [text]))

        code, text = _child(
            godot, game_dir, ["--only", only, "--drop-code", "integer_division"], {}
        )
        covered = "analyser code not covered by the guard: integer_division"
        if code != EXIT_FINDINGS or covered not in text:
            cases.append(("S4 dropped code is a drift finding", code, [text]))

        if cases:
            name, code, texts = cases[0]
            raise SetupError(f"analyser guard self-test failed: {name} (exit {code})\n{texts[0]}")
    finally:
        remove_tree(path)
    print("analyser guard: self-test passed (4 cases)")


