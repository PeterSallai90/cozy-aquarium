"""Analyser warning guard (issue #148).

The project keeps most GDScript analyser codes at their default level (warning), so a new
warning never stops the game or the tests. This guard raises every code that is at level 1 to
error in a throwaway `game/override.cfg`, loads every script outside `res://addons/` through a
generated census scene and fails when the analyser reports anything.

Run it after the import:

    python tools/scripts/check_analyser_warnings.py

Exit codes: 0 clean, 1 findings, 2 setup or tool error (no Godot, not imported, crash, ...).
Python 3.12, standard library only. Godot output goes to a log in the temp directory.

Do not run it in parallel with the test suite in the same checkout.
"""

