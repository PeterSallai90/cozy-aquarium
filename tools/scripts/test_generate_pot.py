class CommandLineTest(GeneratePotTestBase):
    def run_script(self, root: Path, *args: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(SCRIPT), "--root", str(root), *args],
            capture_output=True,
            text=True,
            encoding="utf-8",
            check=False,
        )

    def test_default_run_writes_and_exits_0(self) -> None:
        self.gd('\tprint(tr("menu.main.title"))\n')
        result = self.run_script(self.root)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn(b'msgid "menu.main.title"', self.pot_path().read_bytes())

    def test_check_flag_exits_1_when_stale_and_0_when_fresh(self) -> None:
        self.gd('\tprint(tr("menu.main.title"))\n')
        stale = self.run_script(self.root, "--check")
        self.assertEqual(stale.returncode, 1, stale.stdout + stale.stderr)
        self.assertFalse(self.pot_path().exists())
        self.run_script(self.root)
        fresh = self.run_script(self.root, "--check")
        self.assertEqual(fresh.returncode, 0, fresh.stdout + fresh.stderr)

    def test_a_source_error_exits_1(self) -> None:
        self.gd("\tprint(tr(text))\n")
        result = self.run_script(self.root)
        self.assertEqual(result.returncode, 1)
        self.assertIn("panel.gd:5", result.stdout + result.stderr)

    def test_running_against_the_real_repository_is_up_to_date(self) -> None:
        result = self.run_script(REPO_ROOT, "--check")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_collect_on_the_real_repository_has_no_errors(self) -> None:
        _, errors = generate_pot.collect(REPO_ROOT)
        self.assertEqual(errors, [])


