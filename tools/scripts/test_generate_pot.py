"""Tests for generate_pot.py, written for issue #18 (localization pipeline).

Each test builds a small repository tree in a temporary directory (a game/ folder with sources) and
calls collect(), render_pot() or check(). Assertions use the returned entries, the exit code, file
bytes, and for errors the file name with its line number ("panel.gd:3"). They never assert the
exact wording of an error.

Run: python -m unittest discover -s tools/scripts -p "test_*.py"
"""

from __future__ import annotations

import contextlib
import io
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

import generate_pot

SCRIPT = Path(generate_pot.__file__).resolve()
REPO_ROOT = SCRIPT.parents[2]
POT = "game/localization/messages.pot"

GOLDEN_POT = (
    "# Cozy Aquarium translation template. Generated by tools/scripts/generate_pot.py; "
    "do not edit.\n"
    'msgid ""\n'
    'msgstr ""\n'
    '"Project-Id-Version: Cozy Aquarium\\n"\n'
    '"MIME-Version: 1.0\\n"\n'
    '"Content-Type: text/plain; charset=UTF-8\\n"\n'
    '"Content-Transfer-Encoding: 8bit\\n"\n'
    "\n"
    'msgid "fish.a.b"\n'
    'msgstr ""\n'
    "\n"
    'msgid "fish.a_b"\n'
    'msgstr ""\n'
    "\n"
    'msgid "fish.count"\n'
    'msgid_plural "fish.count.plural"\n'
    'msgstr[0] ""\n'
    'msgstr[1] ""\n'
    "\n"
    'msgid "menu.main.new_aquarium"\n'
    'msgstr ""\n'
)

HEADER_ONLY = GOLDEN_POT[: GOLDEN_POT.index("\n\n") + 1]


class GeneratePotTestBase(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root: Path = Path(tmp.name)
        (self.root / "game" / "localization").mkdir(parents=True)

    def write(self, rel: str, text: str) -> None:
        path = self.root / "game" / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))

    def collect(self) -> tuple[dict[str, str | None], list[str]]:
        return generate_pot.collect(self.root)

    def keys(self) -> dict[str, str | None]:
        entries, errors = self.collect()
        self.assertEqual(errors, [])
        return entries

    def errors(self) -> list[str]:
        _, errors = self.collect()
        self.assertTrue(errors, "expected at least one error")
        return errors

    def assert_error_at(self, file_name: str, line: int) -> None:
        errors = self.errors()
        self.assertTrue(any(f"{file_name}:{line}" in error for error in errors), errors)

    def run_check(self, write: bool) -> tuple[int, str]:
        out = io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
            code = generate_pot.check(self.root, write=write)
        return code, out.getvalue()

    def pot_path(self) -> Path:
        return self.root / POT

    def gd(self, body: str) -> None:
        self.write("ui/panel.gd", "extends Node\n\n\nfunc _ready() -> void:\n" + body)


class GdSourceTest(GeneratePotTestBase):
    def test_tr_with_a_literal_key_is_collected(self) -> None:
        self.gd('\tprint(tr("menu.main.title"))\n')
        self.assertEqual(self.keys(), {"menu.main.title": None})

    def test_atr_is_collected(self) -> None:
        self.gd('\tprint(atr("menu.main.atr"))\n')
        self.assertEqual(self.keys(), {"menu.main.atr": None})

    def test_tr_after_a_dot_is_collected(self) -> None:
        self.gd('\tprint(get_node("x").tr("menu.main.dotted"))\n')
        self.assertEqual(self.keys(), {"menu.main.dotted": None})

    def test_single_quoted_literal_is_collected(self) -> None:
        self.gd("\tprint(tr('menu.main.single'))\n")
        self.assertEqual(self.keys(), {"menu.main.single": None})

    def test_tr_n_records_the_plural_key(self) -> None:
        self.gd('\tprint(tr_n("fish.count", "fish.count.plural", 3))\n')
        self.assertEqual(self.keys(), {"fish.count": "fish.count.plural"})

    def test_atr_n_records_the_plural_key(self) -> None:
        self.gd('\tprint(atr_n("fish.seen", "fish.seen.plural", 3))\n')
        self.assertEqual(self.keys(), {"fish.seen": "fish.seen.plural"})

    def test_sources_in_subfolders_and_the_game_root_are_found(self) -> None:
        self.write("main.gd", 'func _ready() -> void:\n\tprint(tr("menu.root.key"))\n')
        self.write("ui/deep/er/x.gd", 'func _ready() -> void:\n\tprint(tr("menu.deep.key"))\n')
        self.assertEqual(self.keys(), {"menu.root.key": None, "menu.deep.key": None})

    def test_the_same_key_used_twice_is_one_entry(self) -> None:
        self.gd('\tprint(tr("menu.main.title"))\n\tprint(tr("menu.main.title"))\n')
        self.write("ui/other.gd", 'func f() -> void:\n\tprint(tr("menu.main.title"))\n')
        self.assertEqual(self.keys(), {"menu.main.title": None})

    def test_a_call_wrapped_over_several_lines_is_collected(self) -> None:
        self.gd(
            "\tvar text: String = tr_n(\n"
            '\t\t"fish.count",\n'
            '\t\t"fish.count.plural",\n'
            "\t\t3,\n"
            "\t)\n"
            "\tprint(tr(\n"
            '\t\t"menu.wrapped.single"\n'
            "\t))\n"
        )
        self.assertEqual(
            self.keys(), {"fish.count": "fish.count.plural", "menu.wrapped.single": None}
        )

    def test_a_string_with_an_escaped_quote_before_a_call_is_tokenized_correctly(self) -> None:
        self.gd('\tvar s: String = "a\\"b"\n\tprint(tr("menu.after.escape"))\n')
        self.assertEqual(self.keys(), {"menu.after.escape": None})

    def test_lookalike_identifiers_are_not_collected(self) -> None:
        self.gd(
            '\tvar a: String = str("menu.not.a_key")\n'
            '\tvar b: String = "abc".substr(0, 1)\n'
            '\tvar c: int = attr("menu.not.attr")\n'
            '\tvar d: int = my_tr("menu.not.my_tr")\n'
            '\tvar e: int = entr("menu.not.entr")\n'
            '\tvar f: int = tr_x("menu.not.tr_x")\n'
        )
        self.assertEqual(self.keys(), {})

    def test_a_call_in_a_comment_is_not_collected(self) -> None:
        self.gd(
            '\t# print(tr("menu.in.comment"))\n'
            '\tvar a: int = 1  # tr("menu.in.trailing_comment")\n'
            '\t## tr("menu.in.doc_comment")\n'
        )
        self.assertEqual(self.keys(), {})

    def test_a_call_inside_a_string_is_not_collected(self) -> None:
        self.gd(
            '\tvar a: String = "call tr(\\"menu.in.string\\") now"\n'
            "\tvar b: String = 'tr(\"menu.in.single\")'\n"
            '\tvar c: String = """\n'
            'tr("menu.in.triple")\n'
            '"""\n'
        )
        self.assertEqual(self.keys(), {})

    def test_a_function_definition_named_tr_is_not_a_call(self) -> None:
        self.write(
            "ui/helper.gd",
            "func tr(message: String) -> String:\n\treturn message\n\n\n"
            "func tr_n(a: String, b: String, n: int) -> String:\n\treturn a\n",
        )
        self.assertEqual(self.keys(), {})

    def test_a_comment_after_a_string_with_a_hash_inside(self) -> None:
        self.gd('\tvar a: String = "#not a comment"\n\tprint(tr("menu.after.hash"))\n')
        self.assertEqual(self.keys(), {"menu.after.hash": None})

    def test_utf8_sources_with_non_ascii_text_are_read(self) -> None:
        self.gd('\tvar a: String = "Árvíztűrő 熱帯魚"\n\tprint(tr("menu.utf.key"))\n')
        self.assertEqual(self.keys(), {"menu.utf.key": None})


class GdNonLiteralTest(GeneratePotTestBase):
    def test_member_access_ending_in_name_key_is_accepted_and_not_collected(self) -> None:
        self.gd("\tprint(tr(species.name_key))\n")
        self.assertEqual(self.keys(), {})

    def test_identifiers_ending_in_key_are_accepted(self) -> None:
        self.gd("\tprint(tr(entry_key))\n\tprint(tr(key))\n\tprint(tr(a.b.c.description_key))\n")
        self.assertEqual(self.keys(), {})

    def test_plural_with_a_key_expression_and_the_plural_suffix_is_accepted(self) -> None:
        self.gd('\tprint(tr_n(item.name_key, item.name_key + ".plural", 2))\n')
        self.assertEqual(self.keys(), {})

    def test_plural_with_a_different_second_expression_is_rejected(self) -> None:
        self.gd('\tprint(tr_n(item.name_key, other.name_key + ".plural", 2))\n')
        self.assert_error_at("panel.gd", 5)

    def test_plural_with_a_key_expression_and_a_bare_second_argument_is_rejected(self) -> None:
        self.gd("\tprint(tr_n(item.name_key, item.name_key, 2))\n")
        self.assert_error_at("panel.gd", 5)

    def test_concatenated_key_is_rejected_with_file_and_line(self) -> None:
        self.gd('\tvar id: String = "x"\n\tprint(tr("fish." + id))\n')
        self.assert_error_at("panel.gd", 6)

    def test_other_expressions_are_rejected_with_file_and_line(self) -> None:
        for call in (
            "tr(text)",
            "tr(x % y)",
            "tr(str(a))",
            "tr(get_key())",
            "tr(names[0])",
            'tr("menu." + "x")',
            "tr(key + suffix)",
        ):
            with self.subTest(call=call):
                self.write(
                    "ui/panel.gd", f"extends Node\n\n\nfunc _ready() -> void:\n\tprint({call})\n"
                )
                self.assert_error_at("panel.gd", 5)

    def test_a_raw_string_or_name_literal_is_not_a_plain_literal(self) -> None:
        for call in ('tr(r"menu.raw.key")', 'tr(&"menu.name.key")', 'tr(^"menu.path.key")'):
            with self.subTest(call=call):
                self.write(
                    "ui/panel.gd", f"extends Node\n\n\nfunc _ready() -> void:\n\tprint({call})\n"
                )
                self.assert_error_at("panel.gd", 5)

    def test_an_error_means_collect_still_reports_it_for_every_file(self) -> None:
        self.write("ui/a.gd", "func f() -> void:\n\tprint(tr(x))\n")
        self.write("ui/b.gd", "func f() -> void:\n\n\tprint(tr(y))\n")
        errors = self.errors()
        self.assertTrue(any("a.gd:2" in e for e in errors), errors)
        self.assertTrue(any("b.gd:3" in e for e in errors), errors)


class GdLiteralRulesTest(GeneratePotTestBase):
    def test_bad_literal_keys_are_rejected_with_file_and_line(self) -> None:
        for key in ("Menu.Main", "nokey", "foo.bar", "menu..x", "menu.x-y", "menu.x.plural", ""):
            with self.subTest(key=key):
                self.write(
                    "ui/panel.gd",
                    f'extends Node\n\n\nfunc _ready() -> void:\n\tprint(tr("{key}"))\n',
                )
                self.assert_error_at("panel.gd", 5)

    def test_plural_second_argument_must_be_the_key_plus_suffix(self) -> None:
        for second in ('"fish.cnt.plural"', '"fish.count"', '"fish.count.many"', "p", '"x" + ".plural"'):
            with self.subTest(second=second):
                self.gd(f'\tprint(tr_n("fish.count", {second}, n))\n')
                self.assert_error_at("panel.gd", 5)

    def test_plural_with_the_wrong_number_of_arguments_is_rejected(self) -> None:
        for call in (
            'tr_n("fish.count", "fish.count.plural")',
            'tr_n("fish.count", "fish.count.plural", n, "ctx")',
            'tr_n("fish.count")',
        ):
            with self.subTest(call=call):
                self.gd(f"\tprint({call})\n")
                self.assert_error_at("panel.gd", 5)

    def test_a_context_argument_is_rejected(self) -> None:
        self.gd('\tprint(tr("menu.main.title", "ctx"))\n')
        self.assert_error_at("panel.gd", 5)

    def test_tr_without_an_argument_is_rejected(self) -> None:
        self.gd("\tprint(tr())\n")
        self.assert_error_at("panel.gd", 5)

    def test_a_key_that_is_a_plural_form_cannot_be_a_msgid_of_its_own(self) -> None:
        self.gd('\tprint(tr("fish.count.plural"))\n')
        self.assert_error_at("panel.gd", 5)

    def test_singular_and_plural_use_of_one_key_conflict(self) -> None:
        self.write("ui/a.gd", 'func f() -> void:\n\tprint(tr("fish.count"))\n')
        self.write(
            "ui/b.gd", 'func f() -> void:\n\tprint(tr_n("fish.count", "fish.count.plural", 2))\n'
        )
        self.errors()

    def test_two_plural_uses_of_one_key_are_fine(self) -> None:
        self.write(
            "ui/a.gd", 'func f() -> void:\n\tprint(tr_n("fish.count", "fish.count.plural", 2))\n'
        )
        self.write(
            "ui/b.gd", 'func f() -> void:\n\tprint(atr_n("fish.count", "fish.count.plural", 9))\n'
        )
        self.assertEqual(self.keys(), {"fish.count": "fish.count.plural"})


class TscnSourceTest(GeneratePotTestBase):
    def scene(self, *properties: str, section: str = '[node name="L" type="Label" parent="."]') -> None:
        body = "\n".join(properties)
        self.write(
            "ui/scene.tscn",
            '[gd_scene format=3]\n\n[node name="Root" type="Control"]\n\n' + f"{section}\n{body}\n",
        )

    def test_the_four_properties_are_collected(self) -> None:
        self.scene(
            'text = "menu.main.text"',
            'tooltip_text = "menu.main.tooltip"',
            'placeholder_text = "menu.main.placeholder"',
            'title = "menu.main.window_title"',
        )
        self.assertEqual(
            self.keys(),
            {
                "menu.main.text": None,
                "menu.main.tooltip": None,
                "menu.main.placeholder": None,
                "menu.main.window_title": None,
            },
        )

    def test_empty_values_are_skipped(self) -> None:
        self.scene('text = ""', 'tooltip_text = ""', "layout_mode = 2")
        self.assertEqual(self.keys(), {})

    def test_other_properties_are_ignored(self) -> None:
        self.scene('name_text = "Not a key"', 'metadata/note = "Hello"', "custom_minimum_size = 3")
        self.assertEqual(self.keys(), {})

    def test_a_text_that_is_not_a_key_is_rejected_with_file_and_line(self) -> None:
        self.scene('text = "Hello world"')
        # [gd_scene] 1, blank 2, [node Root] 3, blank 4, [node L] 5, the property is line 6.
        self.assert_error_at("scene.tscn", 6)

    def test_bad_values_are_rejected(self) -> None:
        for value in ("Hello", "Menu.Main", "menu", "foo.bar", "menu.x.plural", "menu.a\\nb"):
            with self.subTest(value=value):
                self.scene(f'text = "{value}"')
                self.assert_error_at("scene.tscn", 6)

    def test_a_value_spanning_lines_is_rejected(self) -> None:
        self.scene('text = "menu.main', 'title"')
        self.errors()

    def test_text_in_a_non_node_section_is_ignored(self) -> None:
        self.write(
            "ui/scene.tscn",
            '[gd_scene format=3]\n\n[sub_resource type="Thing" id="Thing_1"]\ntext = "Not a key"\n',
        )
        self.assertEqual(self.keys(), {})

    def test_a_node_name_text_is_not_confused_with_a_property(self) -> None:
        self.write(
            "ui/scene.tscn",
            '[gd_scene format=3]\n\n[node name="text = x" type="Label"]\nlayout_mode = 2\n',
        )
        self.assertEqual(self.keys(), {})


