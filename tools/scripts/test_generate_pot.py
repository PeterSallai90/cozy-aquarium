class RenderPotTest(GeneratePotTestBase):
    ENTRIES: dict[str, str | None] = {
        "menu.main.new_aquarium": None,
        "fish.count": "fish.count.plural",
        "fish.a_b": None,
        "fish.a.b": None,
    }

    def test_golden_output(self) -> None:
        self.assertEqual(generate_pot.render_pot(self.ENTRIES), GOLDEN_POT)

    def test_input_order_does_not_matter(self) -> None:
        reversed_entries = dict(reversed(list(self.ENTRIES.items())))
        self.assertEqual(generate_pot.render_pot(reversed_entries), GOLDEN_POT)

    def test_sorted_by_code_point(self) -> None:
        text = generate_pot.render_pot(self.ENTRIES)
        positions = [text.index(f'msgid "{key}"') for key in ("fish.a.b", "fish.a_b", "fish.count")]
        self.assertEqual(positions, sorted(positions))

    def test_empty_catalog_is_the_header_only(self) -> None:
        text = generate_pot.render_pot({})
        self.assertEqual(text, HEADER_ONLY)
        self.assertTrue(text.endswith('8bit\\n"\n'))

    def test_no_context_reference_comments_or_date(self) -> None:
        text = generate_pot.render_pot(self.ENTRIES)
        self.assertNotIn("msgctxt", text)
        self.assertNotIn("#:", text)
        self.assertNotIn("POT-Creation-Date", text)
        self.assertNotIn("\r", text)
        self.assertTrue(text.endswith("\n"))
        self.assertFalse(text.endswith("\n\n"))

    def test_non_ascii_never_appears_because_keys_are_ascii(self) -> None:
        self.assertTrue(generate_pot.render_pot(self.ENTRIES).isascii())


class CheckTest(GeneratePotTestBase):
    def setUp(self) -> None:
        super().setUp()
        self.write("localization/extra_keys.txt", "menu.main.new_aquarium\nfish.count fish.count.plural\n")
        self.gd('\tprint(tr("fish.a.b"))\n\tprint(tr("fish.a_b"))\n')

    def test_write_creates_the_pot_with_the_golden_bytes(self) -> None:
        code, _ = self.run_check(write=True)
        self.assertEqual(code, 0)
        self.assertEqual(self.pot_path().read_bytes(), GOLDEN_POT.encode("utf-8"))

    def test_the_file_has_no_bom_and_no_carriage_return(self) -> None:
        self.run_check(write=True)
        data = self.pot_path().read_bytes()
        self.assertFalse(data.startswith(b"\xef\xbb\xbf"))
        self.assertNotIn(b"\r", data)
        self.assertTrue(data.endswith(b"\n"))
        self.assertFalse(data.endswith(b"\n\n"))

    def test_two_runs_give_byte_identical_files(self) -> None:
        self.run_check(write=True)
        first = self.pot_path().read_bytes()
        self.run_check(write=True)
        self.assertEqual(self.pot_path().read_bytes(), first)

    def test_check_mode_passes_on_a_fresh_pot_and_writes_nothing(self) -> None:
        self.run_check(write=True)
        before = self.pot_path().stat().st_mtime_ns
        code, _ = self.run_check(write=False)
        self.assertEqual(code, 0)
        self.assertEqual(self.pot_path().stat().st_mtime_ns, before)

    def test_check_mode_fails_on_a_stale_pot_and_leaves_it_alone(self) -> None:
        self.run_check(write=True)
        stale = self.pot_path().read_bytes()
